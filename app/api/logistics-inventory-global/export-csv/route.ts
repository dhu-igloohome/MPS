  "jiadunFactory",
  "jinjianFactory",
  "huameiFactory",
  "shenzhenOffice",
  "taiwanFuhshing",
  "singaporeOffice",
  "cargohubWarehouse",
  "koreaSolityFactory",
  "vietnamSolityFactory",
  "aztechFactory",
  "swrFactory",
  "vsFactory",
  "ibeFactory",
  "smartWarehousing",
  "omniWarehouse",
  "amazonFba",
  "safetyStockAtAmazon",
  "jdmWarehouse",
  "amazon",
  "syw",
  "inTransitStock",
  "inventoryReceivedDate",
  "agingDaysC",
  "unitPriceRmb",
  "unitPriceUsd",
  "batchesInventoryCostUsd",
  "skuInventoryCostUsd",
