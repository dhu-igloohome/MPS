  "batch",
  "batchNoSn",
  "goodToReleaseShipmentFromCm",
  "status",
  "description",
  "stockQtyAvailableForFulfillment",
  "reservedQty",
  "batchesBalanceQty",
  "mpBatchProducedQty",
  "dkksFactory",
  "huiliFactory",
